import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";

// Embed the federation sidecar sources into the bundle so release installs
// (which ship only main.js/manifest.json/styles.css) can materialize the
// sidecar package on first start (see src/sidecar-manager.ts
// ensureSidecarMaterialized). The sidecar package.json must use a
// resolvable-anywhere dependency (github:), not a super-repo-relative file: path.
const sidecarSource = fs.readFileSync(new URL("./sidecar/federation-sidecar.ts", import.meta.url), "utf8");
const sidecarPackageJson = fs.readFileSync(new URL("./sidecar/package.json", import.meta.url), "utf8");

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  define: {
    __SIDECAR_SOURCE__: JSON.stringify(sidecarSource),
    __SIDECAR_PACKAGE_JSON__: JSON.stringify(sidecarPackageJson),
  },
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
